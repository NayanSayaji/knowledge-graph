function TopicHome() {
  const { nodes, sections, stats } = usePortalData();
  const [query, setQuery] = useState("");
  const recent = [...nodes]
    .sort((a, b) => b.updatedAt.localeCompare(a.updatedAt))
    .filter((node) => {
      const haystack = [
        node.title,
        node.summary,
        node.notes,
        node.sections.join(" "),
        node.tags.join(" "),
        node.keywords.join(" "),
        node.resources.map((resource) => resource.url).join(" "),
      ]
        .join(" ")
        .toLowerCase();
      return !query.trim() || haystack.includes(query.trim().toLowerCase());
    });
  return (
    <div className="home-page">
      <section className="home-intro">
        <div>
          <p className="eyebrow">Knowledge topics</p>
          <h1>Simple notes, linked by idea.</h1>
        </div>
        <div className="intro-note">
          <p>A minimal reading list for systems, software, and the links between them.</p>
          <input
            className="home-search"
            value={query}
            onChange={(event) => setQuery(event.target.value)}
            placeholder="Search topics, tags, or links..."
            aria-label="Search topics"
          />
          <div className="stats-inline">
            <span>
              <strong>{stats.topics}</strong> topics
            </span>
            <span>
              <strong>{stats.sections}</strong> sections
            </span>
            <span>
              <strong>{stats.resources}</strong> links
            </span>
          </div>
        </div>
      </section>

      <section className="collection-feed">
        <div className="collection-heading">
          <div>
            <p className="collection-label">The collection</p>
            <h2>All topics</h2>
          </div>
        </div>
        <TopicList nodes={recent.filter((node) => {
          const haystack = [
            node.title,
            node.summary,
            node.notes,
            node.sections.join(" "),
            node.tags.join(" "),
            node.keywords.join(" "),
            node.resources.map((resource) => resource.url).join(" "),
          ]
            .join(" ")
            .toLowerCase();
          return !query.trim() || haystack.includes(query.trim().toLowerCase());
        })} />
      </section>

      <section className="section-accordions">
        <div className="section-heading">
          <div>
            <p className="collection-label">Sections</p>
            <h2>Open a section to see its topics</h2>
          </div>
        </div>
        {sections.map((section) => {
          const grouped = nodes.filter((node) => node.sections.includes(section.name));
          const filtered = grouped.filter((node) => {
            const haystack = [node.title, node.summary, node.notes, node.tags.join(" "), node.keywords.join(" ")]
              .join(" ")
              .toLowerCase();
            return !query.trim() || haystack.includes(query.trim().toLowerCase());
          });
          return (
            <details className="section-accordion" key={section.name}>
              <summary>
                <span>{section.name}</span>
                <small>{filtered.length}</small>
              </summary>
              <TopicList nodes={filtered} />
            </details>
          );
        })}
      </section>
    </div>
  );
}

function SectionRoute() {
  const { nodes } = usePortalData();
  const { name = "" } = useParams();
  const [query, setQuery] = useState("");
  const section = decodeURIComponent(name);
  const selected = nodes.filter((node) => node.sections.includes(section));
  const filtered = query.trim()
    ? selected.filter((node) =>
        [node.title, node.summary, node.tags.join(" "), node.keywords.join(" ")]
          .join(" ")
          .toLowerCase()
          .includes(query.trim().toLowerCase()),
      )
    : selected;

  return (
    <>
      <p className="breadcrumb">
        <Link to="/">Home</Link> / Sections / {section}
      </p>
      <div className="page-heading">
        <p className="eyebrow">Section</p>
        <h1 className="page-title">{section}</h1>
        <p className="lede">{filtered.length} topics in this section.</p>
      </div>
      <input
        className="home-search"
        value={query}
        onChange={(event) => setQuery(event.target.value)}
        placeholder="Search this section..."
        aria-label={`Search ${section}`}
      />
      <TopicList nodes={filtered} />
    </>
  );
}

function TimelineRoute() {
  const { nodes } = usePortalData();
  const months = [...nodes]
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt))
    .reduce<Record<string, KnowledgeNode[]>>((result, node) => {
      const month = new Date(node.createdAt).toLocaleDateString(undefined, {
        month: "long",
        year: "numeric",
      });
      result[month] = [...(result[month] ?? []), node];
      return result;
    }, {});

  return (
    <>
      <div className="page-heading">
        <p className="eyebrow">Timeline</p>
        <h1 className="page-title">Reading history</h1>
        <p className="lede">A chronological index of when each topic was added.</p>
      </div>
      <div className="timeline">
        {Object.entries(months).map(([month, items]) => (
          <section key={month}>
            <h2>{month}</h2>
            <TopicList nodes={items ?? []} />
          </section>
        ))}
      </div>
    </>
  );
}

function StatsRoute() {
  const { nodes, stats } = usePortalData();
  const cards: Array<[string, string | number]> = [
    ["Topics", stats.topics],
    ["Sections", stats.sections],
    ["Links", stats.resources],
    ["Relationships", stats.relationships],
  ];
  return (
    <>
      <div className="page-heading">
        <p className="eyebrow">Stats</p>
        <h1 className="page-title">Library index</h1>
        <p className="lede">A quick look at the size and shape of the collection.</p>
      </div>
      <div className="metric-grid">
        {cards.map(([label, value]) => (
          <div key={label}>
            <strong>{value}</strong>
            <span>{label}</span>
          </div>
        ))}
      </div>
      <TopicList nodes={[...nodes].sort((a, b) => b.relations.length - a.relations.length)} />
    </>
  );
}

const router = createHashRouter([
  {
    path: "/",
    element: <PortalShell />,
    children: [
      { index: true, element: <TopicHome /> },
      { path: "section/:name", element: <SectionRoute /> },
      { path: "timeline", element: <TimelineRoute /> },
      { path: "stats", element: <StatsRoute /> },
    ],
  },
]);

export function PortalRouter({
  graph,
  sections,
  stats,
}: {
  graph: KnowledgeGraph;
  sections: SectionIndex["sections"];
  stats: PortalStats;
}) {
  const active = graph.nodes.filter((node) => !node.archived);
  return (
    <PortalDataProvider
      value={{
        nodes: active,
        sections: sections.length ? sections : buildSectionIndex(active),
        stats: stats ?? derivedStats(active),
      }}
    >
      <RouterProvider router={router} />
    </PortalDataProvider>
  );
}
